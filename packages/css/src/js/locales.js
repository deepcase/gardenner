export function resolveGardenerimLocale(requested) {
  const candidates = (Array.isArray(requested) ? requested : [requested]).filter(Boolean).map(String);
  for (const candidate of candidates) {
    const normalized = candidate.replaceAll("_", "-");
    const exact = gardenerimLocaleNames.find((name) => name.toLowerCase() === normalized.toLowerCase());
    if (exact) return exact;
    const base = normalized.split("-")[0].toLowerCase();
    if (base === "zh") return "zh-CN";
    const match = gardenerimLocaleNames.find((name) => name.toLowerCase().split("-")[0] === base);
    if (match) return match;
  }
  return "en";
}

export function formatGardenerimMessage(template, values = {}) {
  return String(template ?? "").replace(/\{([^{}]+)\}/g, (_, key) => values[key] == null ? `{${key}}` : String(values[key]));
}
